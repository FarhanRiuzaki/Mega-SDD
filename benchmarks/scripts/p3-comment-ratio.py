#!/usr/bin/env python3
"""p3-comment-ratio.py — team feedback #4 (runbook §5 masukan tim #4): comment-lines /
code-lines per file the bolts produced, MEASURED from an arm tree (before vs after).

  python3 benchmarks/scripts/p3-comment-ratio.py <repo> <base-commit> [--json out.json] [--head REF]

Files = `git diff --name-only <base>..<head>` restricted to code extensions, minus vault /
.mega-sdd / lockfiles / node_modules. Per file the counter is deliberately simple and
language-aware only at the comment-syntax level (no parser):
  code        non-blank lines that are not comment lines
  comment     lines that are entirely a comment (line comment, block-comment interior,
              docblock interior, JSX {/* */}, HTML <!-- -->); a trailing comment after code
              counts as code (the line still carries code)
  docblock    subset of `comment`: lines inside /** … */ (PHPDoc / JSDoc) or Python docstrings
  provenance  subset of `comment`: the mega-sdd provenance trailer (Generated by mega-sdd …
              Hard Rules active … and its continuation lines) — LOAD-BEARING (read by
              validate-bolt-artifacts / run-analyze), never a target of the diet; reported
              separately so the ratio can be shown with and without it
  source_anchor subset: `// source: <path>:<line>` (build-uat-e2e --check anchor) — protected
Ratio = comment / code (both excluding blank lines). Numbers are MEASURED on the tree given;
they say nothing about comment QUALITY (KENAPA vs APA) — that is the spot-check's job.
"""
import json, os, re, subprocess, sys

CODE_EXT = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".php", ".py", ".java", ".kt", ".go",
            ".rb", ".cs", ".vue", ".svelte", ".css", ".scss", ".sql", ".prisma", ".sh"}
SKIP_DIR = (".mega-sdd/", "node_modules/", "vendor/", ".git/", "dist/", "build/", "coverage/")
SKIP_NAME = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "composer.lock"}
PROV_START = re.compile(r"Generated by mega-sdd", re.I)
PROV_KEYS = re.compile(r"^\W*(Unit:|Implements claim:|Anchors consulted:|Hard Rules active:|- )")
SRC_ANCHOR = re.compile(r"//\s*source:\s*\S+:\d+\s*$")


def lang(path):
    ext = os.path.splitext(path)[1].lower()
    if path.endswith(".blade.php"):
        return "blade"
    if ext in (".py", ".sh"):
        return "hash"
    if ext in (".css", ".scss"):
        return "cstyle-block-only"
    if ext in (".vue", ".svelte"):
        return "vue"
    if ext == ".sql":
        return "sql"
    return "cstyle"


def count(path, text):
    L = lang(path)
    st = {"code": 0, "comment": 0, "blank": 0, "docblock": 0, "provenance": 0, "source_anchor": 0}
    in_block = False; block_is_doc = False; in_prov = False; in_pystr = False
    for raw in text.splitlines():
        s = raw.strip()
        if not s:
            st["blank"] += 1
            continue
        is_comment = False; is_doc = False
        if L == "hash":
            if in_pystr:
                is_comment = True; is_doc = True
                if s.count('"""') % 2 == 1 or s.count("'''") % 2 == 1:
                    in_pystr = False
            elif s.startswith("#") and not s.startswith("#!"):
                is_comment = True
            elif s.startswith('"""') or s.startswith("'''"):
                is_comment = True; is_doc = True
                q = s[:3]
                if s.count(q) < 2:
                    in_pystr = True
        elif L == "sql":
            if s.startswith("--"):
                is_comment = True
            elif in_block:
                is_comment = True
                if "*/" in s:
                    in_block = False
            elif s.startswith("/*"):
                is_comment = True
                if "*/" not in s[2:]:
                    in_block = True
        else:  # C-style family (+ HTML/blade comments)
            if in_block:
                is_comment = True; is_doc = block_is_doc
                if "*/" in s or "-->" in s or "--}}" in s:
                    in_block = False
            elif s.startswith("/**") or s.startswith("{/**"):
                is_comment = True; is_doc = True
                if "*/" not in s[3:]:
                    in_block = True; block_is_doc = True
            elif s.startswith("/*") or s.startswith("{/*"):
                is_comment = True
                if "*/" not in s[2:]:
                    in_block = True; block_is_doc = False
            elif s.startswith("<!--") or s.startswith("{{--"):
                is_comment = True
                if "-->" not in s and "--}}" not in s:
                    in_block = True; block_is_doc = False
            elif L != "cstyle-block-only" and (s.startswith("//") or (L == "blade" and s.startswith("#"))):
                is_comment = True
        if is_comment:
            st["comment"] += 1
            if is_doc:
                st["docblock"] += 1
            if SRC_ANCHOR.search(s):
                st["source_anchor"] += 1
            if PROV_START.search(s):
                in_prov = True; st["provenance"] += 1
            elif in_prov and PROV_KEYS.match(re.sub(r"^(//|#|\*|<!--|\{\{--|/\*\*?|\{/\*\*?)\s*", "", s)):
                st["provenance"] += 1
            else:
                in_prov = False
        else:
            st["code"] += 1
            in_prov = False
    return st


def main():
    args = sys.argv[1:]
    if len(args) < 2:
        print(__doc__); sys.exit(2)
    repo, base = args[0], args[1]
    head = "HEAD"; out = None
    if "--head" in args:
        head = args[args.index("--head") + 1]
    if "--json" in args:
        out = args[args.index("--json") + 1]
    files = subprocess.run(["git", "-C", repo, "-c", "core.quotepath=false", "diff", "--name-only",
                            "%s..%s" % (base, head)], capture_output=True, text=True, check=True).stdout.split("\n")
    rows = []
    for f in files:
        f = f.strip()
        if not f or any(f.startswith(d) or ("/" + d) in f for d in SKIP_DIR) or os.path.basename(f) in SKIP_NAME:
            continue
        if os.path.splitext(f)[1].lower() not in CODE_EXT and not f.endswith(".blade.php"):
            continue
        p = subprocess.run(["git", "-C", repo, "show", "%s:%s" % (head, f)], capture_output=True, text=True)
        if p.returncode != 0:
            continue  # deleted at head
        st = count(f, p.stdout); st["file"] = f
        st["ratio"] = round(st["comment"] / st["code"], 3) if st["code"] else None
        st["ratio_ex_prov"] = round((st["comment"] - st["provenance"]) / st["code"], 3) if st["code"] else None
        rows.append(st)
    rows.sort(key=lambda r: -(r["ratio"] or 0))
    tot = {k: sum(r[k] for r in rows) for k in ("code", "comment", "blank", "docblock", "provenance", "source_anchor")}
    agg = {"repo": repo, "base": base, "head": head, "files": len(rows), **tot,
           "ratio": round(tot["comment"] / tot["code"], 3) if tot["code"] else None,
           "ratio_ex_prov": round((tot["comment"] - tot["provenance"]) / tot["code"], 3) if tot["code"] else None,
           "docblock_share": round(tot["docblock"] / tot["comment"], 3) if tot["comment"] else None,
           "median_file_ratio": (sorted(r["ratio"] for r in rows if r["ratio"] is not None)[len([r for r in rows if r["ratio"] is not None]) // 2] if rows else None)}
    print("%s @ %s..%s — %d code files" % (repo, base[:7], head, len(rows)))
    print("  code %d · comment %d (docblock %d · provenance %d · source-anchor %d) · blank %d" %
          (tot["code"], tot["comment"], tot["docblock"], tot["provenance"], tot["source_anchor"], tot["blank"]))
    print("  ratio comment/code = %s · ex-provenance = %s · docblock share of comments = %s · median file ratio = %s" %
          (agg["ratio"], agg["ratio_ex_prov"], agg["docblock_share"], agg["median_file_ratio"]))
    print("  %-70s %5s %5s %5s %5s %6s" % ("file", "code", "cmt", "doc", "prov", "ratio"))
    for r in rows:
        print("  %-70s %5d %5d %5d %5d %6s" % (r["file"][-70:], r["code"], r["comment"], r["docblock"], r["provenance"], r["ratio"]))
    if out:
        with open(out, "w") as fh:
            json.dump({"aggregate": agg, "files": rows}, fh, indent=1)


if __name__ == "__main__":
    main()
